//! Event-triggered, bounded clipboard access. No listener, history or persistence.
//!
//! Metadata must be checked before requesting any payload. Native adapters keep
//! the check and read in one snapshot (or verify its change count afterwards).

use std::path::PathBuf;
use std::sync::{Arc, Mutex};

use devtools_core::{ImagePayload, RawPayload};

#[cfg(windows)]
#[path = "clipboard/windows.rs"]
mod native;
#[cfg(target_os = "macos")]
#[path = "clipboard/macos.rs"]
mod native;
#[cfg(target_os = "linux")]
#[path = "clipboard/linux.rs"]
mod native;

pub const TEXT_LIMIT: usize = 2 * 1024 * 1024;
pub const IMAGE_LIMIT: usize = 20 * 1024 * 1024;
pub const FILE_LIMIT: usize = 64;
pub const FILE_LIST_LIMIT: usize = 256 * 1024;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClipboardReadOutcome {
    Payload { sequence: u64, payload: RawPayload },
    Empty,
    ConcealedSkipped,
    TooLarge,
}

#[derive(Debug, thiserror::Error)]
#[error("clipboard access unavailable: {0}")]
pub struct ClipboardError(pub String);

/// Metadata only; callers must never obtain this by reading text or images.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct ConcealmentHints {
    pub formats: Vec<String>,
    pub can_include_in_history: Option<bool>,
    pub kde_password_hint: Option<String>,
}

pub fn is_concealed(hints: &ConcealmentHints) -> bool {
    hints.can_include_in_history == Some(false)
        || hints.kde_password_hint.as_deref() == Some("secret")
        || hints.formats.iter().any(|name| {
            matches!(
                name.as_str(),
                "ExcludeClipboardContentFromMonitorProcessing"
                    | "org.nspasteboard.ConcealedType"
                    | "org.nspasteboard.TransientType"
                    | "org.nspasteboard.AutoGeneratedType"
                    | "com.agilebits.onepassword"
            )
        })
}

/// Enforces the metadata-before-payload boundary and makes the zero-read
/// invariant testable without interacting with a user's real clipboard.
pub(crate) fn guarded_read(
    hints: &ConcealmentHints,
    read_payload: impl FnOnce() -> Result<ClipboardReadOutcome, ClipboardError>,
) -> Result<ClipboardReadOutcome, ClipboardError> {
    if is_concealed(hints) {
        Ok(ClipboardReadOutcome::ConcealedSkipped)
    } else {
        read_payload()
    }
}

/// Keeps X11 clipboard ownership alive after a write. Contains only the current
/// OS clipboard owner, never a history or a serialized payload.
static WRITER: Mutex<Option<arboard::Clipboard>> = Mutex::new(None);
static ACCESS: Mutex<()> = Mutex::new(());

pub fn read() -> Result<ClipboardReadOutcome, ClipboardError> {
    let _guard = ACCESS
        .lock()
        .map_err(|_| ClipboardError("lock poisoned".into()))?;
    native::read()
}

/// `sensitive` is the effective policy: the UI combines the tool capability and
/// `exclude_sensitive_from_clipboard_history` before calling this boundary.
pub fn write_text(text: &str, sensitive: bool) -> Result<(), ClipboardError> {
    let _guard = ACCESS
        .lock()
        .map_err(|_| ClipboardError("lock poisoned".into()))?;
    let mut writer = WRITER
        .lock()
        .map_err(|_| ClipboardError("lock poisoned".into()))?;
    if writer.is_none() {
        *writer = Some(arboard::Clipboard::new().map_err(|e| ClipboardError(e.to_string()))?);
    }
    let clipboard = writer.as_mut().expect("writer initialized");
    #[cfg(target_os = "macos")]
    use arboard::SetExtApple;
    #[cfg(target_os = "linux")]
    use arboard::SetExtLinux;
    #[cfg(windows)]
    use arboard::SetExtWindows;
    let set = clipboard.set();
    #[cfg(windows)]
    let set = if sensitive {
        set.exclude_from_monitoring().exclude_from_history()
    } else {
        set
    };
    #[cfg(any(target_os = "macos", target_os = "linux"))]
    let set = if sensitive {
        set.exclude_from_history()
    } else {
        set
    };
    set.text(text).map_err(|e| ClipboardError(e.to_string()))?;
    #[cfg(target_os = "macos")]
    if sensitive {
        native::mark_transient();
    }
    Ok(())
}

pub fn classify_payload(
    files: Vec<PathBuf>,
    image: Option<ImagePayload>,
    text: Option<Arc<str>>,
) -> ClipboardReadOutcome {
    let payload = if !files.is_empty() {
        if files.len() > FILE_LIMIT
            || files.iter().map(|p| p.as_os_str().len()).sum::<usize>() > FILE_LIST_LIMIT
        {
            return ClipboardReadOutcome::TooLarge;
        }
        RawPayload::Files(files)
    } else if let Some(image) = image {
        if image.bytes.len() > IMAGE_LIMIT {
            return ClipboardReadOutcome::TooLarge;
        }
        RawPayload::Image(image)
    } else if let Some(text) = text.filter(|t| !t.is_empty()) {
        if text.len() > TEXT_LIMIT {
            return ClipboardReadOutcome::TooLarge;
        }
        RawPayload::Text(text)
    } else {
        return ClipboardReadOutcome::Empty;
    };
    ClipboardReadOutcome::Payload {
        sequence: 0,
        payload,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn concealment_markers_are_checked_without_payload() {
        for format in [
            "ExcludeClipboardContentFromMonitorProcessing",
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
        ] {
            assert!(is_concealed(&ConcealmentHints {
                formats: vec![format.into()],
                ..Default::default()
            }));
        }
        assert!(is_concealed(&ConcealmentHints {
            can_include_in_history: Some(false),
            ..Default::default()
        }));
        assert!(is_concealed(&ConcealmentHints {
            kde_password_hint: Some("secret".into()),
            ..Default::default()
        }));
        assert!(!is_concealed(&ConcealmentHints {
            can_include_in_history: Some(true),
            kde_password_hint: Some("public".into()),
            ..Default::default()
        }));
    }

    #[test]
    fn concealed_snapshot_never_invokes_payload_reader() {
        let hints = ConcealmentHints {
            formats: vec!["org.nspasteboard.ConcealedType".into()],
            ..Default::default()
        };
        assert_eq!(
            guarded_read(&hints, || panic!("payload must not be requested")).unwrap(),
            ClipboardReadOutcome::ConcealedSkipped
        );
        assert_eq!(
            guarded_read(&ConcealmentHints::default(), || Ok(
                ClipboardReadOutcome::Empty
            ))
            .unwrap(),
            ClipboardReadOutcome::Empty
        );
    }

    #[test]
    fn classification_is_files_then_image_then_text_and_bounded() {
        let image = ImagePayload {
            width: 1,
            height: 1,
            bytes: Arc::from([1u8]),
        };
        assert!(matches!(
            classify_payload(
                vec!["file.png".into()],
                Some(image.clone()),
                Some("text".into())
            ),
            ClipboardReadOutcome::Payload {
                payload: RawPayload::Files(_),
                ..
            }
        ));
        assert!(matches!(
            classify_payload(vec![], Some(image), Some("text".into())),
            ClipboardReadOutcome::Payload {
                payload: RawPayload::Image(_),
                ..
            }
        ));
        assert_eq!(
            classify_payload(vec![], None, Some("x".repeat(TEXT_LIMIT + 1).into())),
            ClipboardReadOutcome::TooLarge
        );
        assert_eq!(
            classify_payload(vec![], None, Some("".into())),
            ClipboardReadOutcome::Empty
        );
    }

    #[test]
    fn snapshots_cannot_be_persisted() {
        static_assertions::assert_not_impl_any!(ClipboardReadOutcome: serde::Serialize, serde::de::DeserializeOwned);
        static_assertions::assert_not_impl_any!(ConcealmentHints: serde::Serialize, serde::de::DeserializeOwned);
    }
}
